export const breedStats = {
  totalBreeds: breeds.length,
  indigenousCattle: breeds.filter((b) => b.type === "cattle" && b.category === "indigenous").length,
  buffaloes: breeds.filter((b) => b.type === "buffalo").length,
  exotic: breeds.filter((b) => b.category === "exotic").length,
  endangered: breeds.filter((b) => b.conservationStatus === "endangered").length,
};

export function getBreedById(id: string) {
  return breeds.find((b) => b.id === id);
}

export function filterBreeds(opts: {
  query?: string;
  category?: BreedCategory | "all";
  type?: BovineType | "all";
  use?: BreedUse | "all";
}) {
  return breeds.filter((b) => {
    if (opts.query) {
      const q = opts.query.toLowerCase();
      const match =
        b.name.toLowerCase().includes(q) ||
        b.origin.toLowerCase().includes(q) ||
        b.region.toLowerCase().includes(q) ||
        b.description.toLowerCase().includes(q);
      if (!match) return false;
    }
    if (opts.category && opts.category !== "all" && b.category !== opts.category) return false;
    if (opts.type && opts.type !== "all" && b.type !== opts.type) return false;
    if (opts.use && opts.use !== "all" && b.primaryUse !== opts.use) return false;
    return true;
  });
}
